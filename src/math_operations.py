def add(a, b):
    """
    Returns the sum of a and b.
    Args:
        a (int|float): First operand
        b (int|float): Second operand
    Returns:
        int|float: Sum of a and b
    """
    return a + b

def subtract(a, b):
    """
    Returns the difference of a and b (a - b).
    Args:
        a (int|float): First operand
        b (int|float): Second operand
    Returns:
        int|float: Difference of a and b
    """
    return a - b
